import { mkdtempSync,writeFileSync,readFileSync,existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join,resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const root=resolve(import.meta.dirname,'..'),npm=process.env.npm_execpath;
if(!npm)throw new Error('Run this check through npm run test:package.');
const work=mkdtempSync(join(tmpdir(),'uarchdraw-package-'));
function run(cwd,args){const r=spawnSync(process.execPath,args,{cwd,encoding:'utf8'});if(r.status!==0)throw new Error(r.stderr||r.stdout||`Exit ${r.status}`);return r.stdout;}
const packed=JSON.parse(run(root,[npm,'pack','--ignore-scripts','--json','--pack-destination',work]))[0];
const archive=join(work,packed.filename);
assert.ok(packed.files.some(f=>f.path==='assets/DejaVuSans.ttf'));
assert.ok(packed.files.some(f=>f.path==='examples/05-rv32i-forwarding.uarch'));
assert.ok(packed.files.some(f=>f.path==='examples/tutorials/01.md'));
assert.ok(packed.files.some(f=>f.path==='examples/tutorials/images/01-03-connect.png'));
assert.ok(!packed.files.some(f=>f.path.startsWith('dist/test/')));
assert.ok(!packed.files.some(f=>/^(scripts|src|output|node_modules|docs\/reviews)\//.test(f.path)));
assert.ok(!packed.files.some(f=>/^dist\/(pipeline|rv32i|review)\./.test(f.path)));
writeFileSync(join(work,'package.json'),JSON.stringify({name:'uarchdraw-install-check',version:'1.0.0',private:true,type:'module'}));
run(work,[npm,'install','--omit=dev','--no-audit','--no-fund',archive]);
const result=JSON.parse(run(work,[npm,'exec','--offline','--','uarchdraw','check','node_modules/uarchdraw/examples/05-rv32i-forwarding.uarch']));
assert.equal(result.ok,true);assert.equal(result.metrics.labeledNets,49);
run(work,[npm,'exec','--offline','--','uarchdraw','render','node_modules/uarchdraw/examples/01-first-diagram.uarch','-o','rendered/first']);
assert.ok(existsSync(join(work,'rendered/first.svg')));
assert.deepEqual([...readFileSync(join(work,'rendered/first.png')).subarray(0,8)],[137,80,78,71,13,10,26,10]);
const program=`import {readFileSync} from 'node:fs';import {parseUarch,compile} from 'uarchdraw';const d=await parseUarch(readFileSync('node_modules/uarchdraw/examples/01-first-diagram.uarch','utf8'));console.log(compile(d).audit.ok);`;
assert.equal(run(work,['--input-type=module','-e',program]).trim(),'true');
run(work,[npm,'exec','--offline','--','uarchdraw','init','selector.uarch','--template','selector']);
const automatic=JSON.parse(run(work,[npm,'exec','--offline','--','uarchdraw','check','selector.uarch']));
assert.equal(automatic.ok,true);assert.equal(automatic.metrics.nets,10);
const overview=JSON.parse(run(work,[npm,'exec','--offline','--','uarchdraw','check','node_modules/uarchdraw/examples/14-hierarchical-datapath.uarch','--overview']));
assert.equal(overview.ok,true);assert.equal(overview.metrics.nets,2);
const learning=JSON.parse(run(work,[npm,'exec','--offline','--','uarchdraw','check','node_modules/uarchdraw/examples/tutorials/04-03-sixteen.uarch']));
assert.equal(learning.ok,true);assert.equal(learning.metrics.nets,18);
console.log(`Package check passed: installed CLI, RV32I, SVG/PNG, font, API, version-2 init, hierarchy and the sixteen-input learning checkpoint. Archive: ${archive}`);
